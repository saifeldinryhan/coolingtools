// يمكن إضافة دوال مساعدة للبحث عن كود معين
function findErrorCode(company, deviceType, inverterType, code) {
  const companyData = errorCodes[company];
  if (!companyData) return null;
  const deviceData = companyData[deviceType];
  if (!deviceData) return null;
  const typeData = deviceData[inverterType];
  if (!typeData) return null;
  return typeData.find(item => item.code === code) || null;
}

